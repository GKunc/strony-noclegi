#!/usr/bin/env node
// Builds and deploys the contact form worker (worker/form.js) to Cloudflare, with the email templates
// from emails/ and the settings from site.config.json baked in.
// One-time set-up (agency-wide) is in the publish skill: "Contact form emails, one-time set-up".
//
// Usage:
//   node tools/form-worker.mjs bundle    build .worker/ only (used by the checks and tests)
//   node tools/form-worker.mjs deploy    build + deploy; writes the worker URL into FORM_ENDPOINT
//                                        (--ci: used by the workflow; never writes files, fails if the URL changed)
//   node tools/form-worker.mjs version   print the version this repo would deploy (the live one: GET <worker>?version)
//   node tools/form-worker.mjs secrets   give this worker the agency keys (from the secrets file, never printed)
//                                        and a fresh test token for node tools/form-test.mjs --send
//   node tools/form-worker.mjs name      print the worker name for this site
// Deploying uses Wrangler (Cloudflare's CLI) with its own browser sign-in: `npx wrangler login`, once per computer.
import { spawnSync } from 'node:child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createHash, randomBytes } from 'node:crypto';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { ROOT, WRANGLER, loadConfig, read, setConfig, siteUrl } from './lib.mjs';
import { buildEmails } from './emails.mjs';

export const SECRETS_FILE = process.env.FORM_SECRETS || join(homedir(), '.config/landing-tools/form-secrets.json');
export const TEST_TOKENS_FILE = join(homedir(), '.config/landing-tools/form-test-tokens.json');
export const WORKER_DIR = join(ROOT, '.worker');
const COMPATIBILITY_DATE = '2025-06-01';

/** Cloudflare worker name for this site: from SITE_URL, lowercase, max 63 chars. */
export function workerName(config) {
  const u = new URL(String(config.SITE_URL));
  const slug = (u.host + u.pathname).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return `${slug.slice(0, 57).replace(/-+$/, '')}-form`;
}

/** What the worker is built from: site settings, rendered email templates and the worker code. */
export function workerSource(config = loadConfig()) {
  const missing = ['SITE_URL', 'EMAIL_FROM', 'CONTACT_EMAIL', 'BRAND'].filter((k) => !config[k]);
  if (missing.length) throw new Error(`Set ${missing.join(', ')} in site.config.json first.`);
  const url = siteUrl(config);
  const { origin, host } = new URL(url);
  const twin = host.startsWith('www.') ? host.slice(4) : `www.${host}`; // custom domains: apex and www
  const hosts = host.endsWith('.github.io') ? [host] : [host, twin];
  const brand = String(config.BRAND).replace(/["<>\r\n]/g, '');
  const site = {
    url,
    origins: hosts.map((h) => origin.replace(host, h)),
    hosts,
    from: `"${brand}" <${config.EMAIL_FROM}>`,
    notifyTo: config.FORM_NOTIFY_TO || config.CONTACT_EMAIL,
    replyTo: config.CONTACT_EMAIL,
    contact: config.CONTACT_EMAIL,
  };
  const emails = buildEmails(config);
  const code = ['form.js', 'render.js'].map((f) => read(join(ROOT, 'worker', f))).join('\n');
  // Same inputs -> same version, so the monitor can tell whether the live worker matches the repo.
  site.version = createHash('sha256').update(JSON.stringify([site, emails, code])).digest('hex').slice(0, 12);
  return { site, emails };
}

/** Writes .worker/ (form.js, render.js, site.js). Returns the directory. */
export function bundle(config = loadConfig(), out = WORKER_DIR) {
  const { site, emails } = workerSource(config);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const f of ['form.js', 'render.js']) copyFileSync(join(ROOT, 'worker', f), join(out, f));
  writeFileSync(join(out, 'site.js'), `// Generated by tools/form-worker.mjs from site.config.json and emails/. Do not edit.\nexport const SITE = ${JSON.stringify(site, null, 2)};\nexport const EMAILS = ${JSON.stringify(emails, null, 2)};\n`);
  return out;
}

function wrangler(args, opts = {}) {
  return spawnSync('npx', ['--yes', WRANGLER, ...args], { cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32', ...opts });
}

function deploy() {
  const ci = process.argv.includes('--ci');
  const config = loadConfig();
  if (ci && !/\.workers\.dev\/?$/.test(config.FORM_ENDPOINT || '')) {
    console.log('FORM_ENDPOINT is not a form worker; nothing to deploy.');
    return;
  }
  bundle(config);
  const name = workerName(config);
  console.log(`Deploying worker "${name}"…`);
  const r = wrangler(['deploy', join('.worker', 'form.js'), '--name', name, '--compatibility-date', COMPATIBILITY_DATE], { stdio: ['inherit', 'pipe', 'pipe'] });
  const output = `${r.stdout || ''}${r.stderr || ''}`;
  process.stdout.write(output);
  if (r.status !== 0) {
    if (/not logged in|login|authenticat/i.test(output)) console.error('\nWrangler is not signed in: the user runs `npx wrangler login` once (it opens the browser).');
    process.exit(1);
  }
  const url = output.match(/https:\/\/[a-z0-9.-]+\.workers\.dev/i)?.[0];
  if (!url) { console.error('Deployed, but could not find the workers.dev URL in the output above. Set FORM_ENDPOINT by hand.'); process.exit(1); }
  if (ci) {
    if (config.FORM_ENDPOINT.replace(/\/$/, '') !== url) { console.error(`The worker URL is now ${url} but FORM_ENDPOINT is ${config.FORM_ENDPOINT}: deploy once by hand to update it.`); process.exit(1); }
    console.log(`\nWorker ${workerSource(config).site.version} live at ${url}.`);
    return;
  }
  if (config.FORM_ENDPOINT !== url) {
    setConfig('FORM_ENDPOINT', url);
    console.log(`\nFORM_ENDPOINT set to ${url} in site.config.json (commit and push so the page uses it).`);
  } else console.log(`\nWorker updated at ${url}.`);
  if (!existsSync(TEST_TOKENS_FILE) || !JSON.parse(read(TEST_TOKENS_FILE))[name]) console.log('First deploy of this worker: run node tools/form-worker.mjs secrets.');
}

function secrets() {
  const config = loadConfig();
  const name = workerName(config);
  if (!existsSync(SECRETS_FILE)) {
    console.error(`No ${SECRETS_FILE}. Do the one-time set-up in the publish skill ("Contact form emails, one-time set-up").`);
    process.exit(1);
  }
  let keys;
  try { keys = JSON.parse(read(SECRETS_FILE)); } catch (e) { console.error(`${SECRETS_FILE} is not valid JSON: ${e.message}`); process.exit(1); }
  for (const k of ['RESEND_API_KEY', 'TURNSTILE_SECRET_KEY']) if (!keys[k]) { console.error(`${SECRETS_FILE} has no ${k}.`); process.exit(1); }

  const tokens = existsSync(TEST_TOKENS_FILE) ? JSON.parse(read(TEST_TOKENS_FILE)) : {};
  tokens[name] = randomBytes(24).toString('hex');
  const tmp = join(tmpdir(), `form-secrets-${process.pid}.json`);
  writeFileSync(tmp, JSON.stringify({ RESEND_API_KEY: keys.RESEND_API_KEY, TURNSTILE_SECRET_KEY: keys.TURNSTILE_SECRET_KEY, FORM_TEST_TOKEN: tokens[name] }), { mode: 0o600 });
  try {
    const r = wrangler(['secret', 'bulk', tmp, '--name', name], { stdio: ['ignore', 'pipe', 'pipe'] });
    // Wrangler prints only secret names, never values; show its output for errors.
    process.stdout.write(`${r.stdout || ''}${r.stderr || ''}`);
    if (r.status !== 0) process.exit(1);
  } finally {
    rmSync(tmp, { force: true });
  }
  mkdirSync(dirname(TEST_TOKENS_FILE), { recursive: true });
  writeFileSync(TEST_TOKENS_FILE, JSON.stringify(tokens, null, 2));
  chmodSync(TEST_TOKENS_FILE, 0o600);
  console.log(`\nSecrets set for "${name}". Test it: node tools/form-test.mjs --send (ask the user first).`);
}

const commands = {
  bundle: () => console.log(`Built ${bundle()}`),
  deploy,
  secrets,
  name: () => console.log(workerName(loadConfig())),
  version: () => console.log(workerSource().site.version),
};
if (process.argv[1] && process.argv[1].endsWith('form-worker.mjs')) {
  const cmd = commands[process.argv[2]];
  if (!cmd) { console.error('Usage: node tools/form-worker.mjs bundle | deploy [--ci] | secrets | name | version'); process.exit(1); }
  try { await cmd(); } catch (e) { console.error(e.message); process.exit(1); }
}
